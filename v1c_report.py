def fmt(x, n=4):
    if x is None:
        return "—"
    if isinstance(x, float):
        return ("%.*f" % (n, x)).replace(".", ",")
    return str(x)


def _kc_composition(V):
    """KC->MBON input composition for each T38 type, by Kenyon-cell subtype.

    Static read of the frozen connectivity table with the same loader and
    the same substitution mask the stage uses; the simulator is not run.
    Returns (shares of the weight sum by subtype, weight sum not from KCa'b').
    """
    from model import default_params as dp

    neurons, con = V.load_substrate()
    role = dict(zip(neurons.root_id, neurons.mb_role))
    typ = dict(zip(neurons.root_id, neurons.hemibrain_type.astype(str)))
    kept, _ = V.apply_dan_mask(con, role)
    pre = kept.Presynaptic_ID.map(role)
    post = kept.Postsynaptic_ID.map(role)
    e = kept[(pre == "Kenyon_Cell") & (post == "MBON")]
    w_syn = float(dp["w_syn"] / (0.001 * 1.0))
    ws = e["Excitatory x Connectivity"].to_numpy() * w_syn

    def sub(i):
        t = typ.get(i, "")
        for p in ("KCab", "KCa'b'", "KCg"):
            if t.startswith(p):
                return p
        return "прочие"

    comp, tot = {}, {}
    kc = [sub(i) for i in e.Presynaptic_ID]
    mb = [typ.get(i, "") for i in e.Postsynaptic_ID]
    for t, k, x in zip(mb, kc, ws):
        if t not in V.T38:
            continue
        comp.setdefault(t, {}).setdefault(k, 0.0)
        comp[t][k] += float(x)
        if k != "KCa'b'":
            tot[t] = tot.get(t, 0.0) + float(x)
    for t in V.T38:
        tot.setdefault(t, 0.0)
    return comp, tot


